"""The released code builds the same prompts and answers as the evaluated snapshot.

`golden.json` was generated by the exact source that produced the submitted run,
on the synthetic requests in `golden_requests.py`. Set MORJ_TOKENIZER to the tokenizer
overlay the service builds (~/.cache/morj/bf16/morj/tokenizer) or to a google/gemma-4-31B-it
directory: both give byte-identical tokenizer files, so the prompts are the same.
"""
import hashlib
import json
import os
import random
from pathlib import Path

import pytest

from morj.method import combine, disagreeing
from tests.golden_requests import REQUESTS, readout

TOKENIZER = os.environ.get('MORJ_TOKENIZER')  # read at import: conftest clears MORJ_* per test
GOLDEN = json.loads(Path(__file__).with_name('golden.json').read_text())


def assert_same_answers(got, want, name):
    """Decisions must match exactly; numbers to 1e-12 (math.log/exp round differently across C libraries)."""
    assert list(got) == list(want), name
    for key, answer in want.items():
        assert got[key]['type'] == answer['type'] and got[key].get('choice') == answer.get('choice'), (name, key)
        for field in ('noul', 'score', 'confidence'):
            if field in answer:
                assert got[key][field] == pytest.approx(answer[field], rel=1e-12, abs=1e-12), (name, key, field)
        if 'probabilities' in answer:
            assert list(got[key]['probabilities']) == list(answer['probabilities']), (name, key)
            assert list(got[key]['probabilities'].values()) == pytest.approx(
                list(answer['probabilities'].values()), rel=1e-12, abs=1e-12), (name, key)


def digest(branches):
    return [[b.question, b.kind, list(b.order), len(b.input_ids),
             hashlib.sha256(json.dumps([b.input_ids, list(b.label_ids)]).encode()).hexdigest()] for b in branches]


@pytest.mark.skipif(not TOKENIZER, reason='needs the Gemma tokenizer (MORJ_TOKENIZER)')
def test_branches_gate_and_answers_match_the_evaluated_snapshot():
    from transformers import AutoTokenizer
    from morj.prompt import Builder
    tokenizer_file = Path(TOKENIZER) / 'tokenizer.json'
    assert hashlib.sha256(tokenizer_file.read_bytes()).hexdigest() == GOLDEN['tokenizer_sha256']
    builder = Builder(AutoTokenizer.from_pretrained(TOKENIZER, local_files_only=True))
    assert [c['name'] for c in GOLDEN['cases']] == list(REQUESTS)
    for case in GOLDEN['cases']:
        state, questions = REQUESTS[case['name']]
        keys = list(questions)
        branches = [b for start in range(0, len(keys), 128)
                    for b in builder.prepare(state, {k: questions[k] for k in keys[start:start + 128]})]
        assert digest(branches) == case['first_pass'], case['name']
        rng = random.Random(case['name'])
        rows = readout(rng, branches)
        gated = disagreeing(branches, rows)
        assert gated == case['gated'], case['name']
        extra = [b for start in range(0, len(gated), 128)
                 for b in builder.extra(state, {k: questions[k] for k in gated[start:start + 128]})]
        assert digest(extra) == case['second_pass'], case['name']
        answers = combine(questions, branches + extra, rows + readout(rng, extra))['answers']
        assert_same_answers(answers, case['answers'], case['name'])
